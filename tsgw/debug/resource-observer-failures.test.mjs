import assert from "node:assert/strict";
import test from "node:test";
import { snapshot, harness, answer, queriedId, bootstrap, tick, flush } from "./resource-observer-fixtures.mjs";

test("one ID's failure retains only that ID's success, time and failure counters; resources fires on every completion", async () => {
  const h = harness();
  await bootstrap(h);
  for (const at of [2000, 4000, 6000]) await tick(h, at);
  const before = h.cache;
  const callbacks = h.resources.length;
  h.pollAt(8000);
  h.time(8090);
  answer(h.debug.at(-1), {}, 503);
  await flush();
  assert.equal(h.resources.length, callbacks + 1);
  assert.equal(h.cache.a.reply, before.a.reply);
  assert.equal(h.cache.a.receivedAt, 2000);
  assert.equal(h.cache.a.reply.now, 3000);
  assert.equal(h.cache.a.failure.kind, "http");
  assert.equal(h.cache.a.failure.status, 503);
  assert.equal(h.cache.a.failure.at, 8090);
  assert.equal(h.cache.a.requests, 2);
  assert.equal(h.cache.a.failures, 1);
  assert.equal(h.cache.a.consecutiveFailures, 1);
  assert.equal(h.cache.b, before.b);
  assert.equal(h.cache.c, before.c);
  assert.equal(h.cache.c.failure, null);
  await tick(h, 10000);
  await tick(h, 12000);
  await tick(h, 14000);
  assert.equal(h.cache.a.failure, null);
  assert.equal(h.cache.a.failures, 1);
  assert.equal(h.cache.a.consecutiveFailures, 0);
  h.observer.dispose();
});

test("A success then B failure keeps global roster/totals stale without borrowing A detail; C success recovers", async () => {
  const h = harness();
  await bootstrap(h);
  h.pollAt(2000);
  const aReply = snapshot(["a", "b", "c"], "a", 31000);
  aReply.server.sseTotal = 17;
  aReply.server.eventStreams.total = 9;
  h.time(2140);
  answer(h.debug.at(-1), aReply);
  await flush();
  const aResource = h.cache.a;
  const aGlobal = h.readings.at(-1);
  const catalogs = [...h.catalogs];
  assert.equal(aGlobal.reply.session, null);
  assert.equal(aResource.reply.session.sessionId, "a");
  assert.equal(aGlobal.receivedAt, 2140);
  assert.equal(aGlobal.roundTripMs, 140);

  h.pollAt(4000);
  assert.equal(queriedId(h.debug.at(-1)), "b");
  h.time(4090);
  answer(h.debug.at(-1), {}, 503);
  await flush();
  const failed = h.readings.at(-1);
  assert.equal(failed.sessionId, "b", "failure is attributed to the actual requested target");
  assert.equal(failed.reply.server, aReply.server);
  assert.equal(failed.reply.sessions, aReply.sessions);
  assert.equal(failed.reply.now, 31000);
  assert.equal(failed.reply.server.wrappers.alive, 3);
  assert.equal(failed.reply.server.sseTotal, 17);
  assert.equal(failed.reply.server.eventStreams.total, 9);
  assert.equal(failed.reply.session, null, "global retention cannot lend A's detail to B");
  assert.equal(failed.receivedAt, 2140, "a failed poll does not refresh the overall snapshot");
  assert.equal(failed.roundTripMs, 140, "duration remains that of the retained successful snapshot");
  assert.deepEqual(failed.failure, { kind: "http", status: 503, at: 4090 });
  assert.equal(failed.requests, 3);
  assert.equal(failed.failures, 1);
  assert.equal(failed.consecutiveFailures, 1);
  assert.deepEqual(Object.keys(h.cache), ["a", "b", "c"]);
  assert.equal(h.cache.a, aResource);
  assert.equal(h.cache.a.reply.session.sessionId, "a");
  assert.equal(h.cache.b.reply, null, "B still has no observed detail");
  assert.equal(h.cache.b.receivedAt, null);
  assert.deepEqual(h.cache.b.failure, failed.failure);
  assert.equal(h.cache.b.requests, 1);
  assert.equal(h.cache.c.reply, null);
  assert.deepEqual(h.catalogs, catalogs);
  assert.equal(aReply.session.sessionId, "a", "global sanitizing must not mutate the resource reply");

  assert.equal(await tick(h, 6000, ["a", "b", "c"], 35000), "c");
  const recovered = h.readings.at(-1);
  assert.equal(recovered.reply.now, 35000);
  assert.equal(recovered.reply.session, null);
  assert.equal(recovered.receivedAt, 6000);
  assert.equal(recovered.failure, null);
  assert.equal(recovered.requests, 4);
  assert.equal(recovered.failures, 1);
  assert.equal(recovered.consecutiveFailures, 0);
  assert.equal(h.cache.c.reply.session.sessionId, "c");
  assert.equal(h.cache.b.reply, null);
  assert.equal(h.cache.b.failure.kind, "http", "C recovery cannot clear B's own failure");
  h.observer.dispose();
});

test("consecutive cross-target failures retain the same last good global snapshot and original success time", async () => {
  const h = harness();
  await bootstrap(h);
  await tick(h, 2000);
  const good = h.readings.at(-1);
  h.pollAt(4000);
  answer(h.debug.at(-1), {}, 503);
  await flush();
  const failedB = h.readings.at(-1);
  h.pollAt(6000);
  h.debug.at(-1).reject(new Error("offline"));
  await flush();
  const failedC = h.readings.at(-1);
  assert.equal(failedC.reply, failedB.reply);
  assert.equal(failedC.reply.session, null);
  assert.equal(failedC.reply.sessions, good.reply.sessions);
  assert.equal(failedC.receivedAt, good.receivedAt);
  assert.equal(failedC.roundTripMs, good.roundTripMs);
  assert.equal(failedC.failure.kind, "network");
  assert.equal(failedC.sessionId, "c");
  assert.equal(failedC.requests, 4);
  assert.equal(failedC.failures, 2);
  assert.equal(failedC.consecutiveFailures, 2);
  assert.equal(h.cache.b.failure.kind, "http");
  assert.equal(h.cache.c.failure.kind, "network");
  assert.equal(h.cache.c.consecutiveFailures, 1, "per-ID counters do not inherit global failures");
  h.observer.dispose();
});

test("first detail failure is still unobserved; null/mismatched detail cannot poison an ID's cache", async () => {
  const h = harness();
  await bootstrap(h);
  h.pollAt(2000);
  answer(h.debug.at(-1), {}, 500);
  await flush();
  assert.equal(h.cache.a.reply, null);
  assert.equal(h.cache.a.receivedAt, null);
  assert.equal(h.cache.a.failure.kind, "http");
  h.pollAt(4000);
  answer(h.debug.at(-1), snapshot(["a", "b", "c"], "wrong-id"));
  await flush();
  assert.equal(h.cache.b.reply, null);
  assert.equal(h.cache.b.receivedAt, null);
  assert.equal(h.cache.b.failure.kind, "invalid");
  assert.equal(h.cache["wrong-id"], undefined);
  h.pollAt(6000);
  answer(h.debug.at(-1), snapshot(["a", "b", "c"]));
  await flush();
  assert.equal(h.cache.c.reply, null);
  assert.equal(h.cache.c.failure.kind, "invalid");
  await tick(h, 8000);
  const old = h.cache.a;
  await tick(h, 10000);
  await tick(h, 12000);
  h.pollAt(14000);
  answer(h.debug.at(-1), snapshot(["a", "b", "c"], "b"));
  await flush();
  assert.equal(h.cache.a.reply, old.reply);
  assert.equal(h.cache.a.receivedAt, old.receivedAt);
  assert.equal(h.cache.a.failure.kind, "invalid");
  h.observer.dispose();
});

test("network, invalid envelope and timeout use the base validator and timeout; no per-session timers", async () => {
  const h = harness();
  await bootstrap(h);
  h.pollAt(2000);
  assert.equal(h.timers.size, 1);
  h.debug.at(-1).reject(new Error("offline"));
  await flush();
  assert.equal(h.cache.a.failure.kind, "network");
  h.pollAt(4000);
  answer(h.debug.at(-1), { bad: true });
  await flush();
  assert.equal(h.cache.b.failure.kind, "invalid");
  h.pollAt(6000);
  assert.equal(h.timers.size, 1);
  for (const timer of [...h.timers.values()]) { assert.equal(timer.ms, 5000); timer.fn(); }
  await flush();
  assert.equal(h.cache.c.failure.kind, "timeout");
  assert.equal(h.observer.inFlightSince(), null);
  assert.equal(h.timers.size, 0);
  assert.equal(await tick(h, 12000), "a");
  assert.equal(h.maxActiveDebug, 1);
  h.observer.dispose();
});

test("failed bootstrap retries null; it cannot invent residents from the catalog", async () => {
  const h = harness();
  h.pollAt(0);
  answer(h.debug.at(-1), {}, 500);
  await flush();
  assert.deepEqual(h.cache, {}, "catalog-only IDs are not resident observations");
  assert.equal(h.readings.at(-1).reply, null, "without any good global snapshot, failure remains unobserved");
  assert.equal(h.readings.at(-1).receivedAt, null);
  h.pollAt(2000);
  assert.equal(queriedId(h.debug.at(-1)), null);
  answer(h.debug.at(-1), snapshot(["a", "b", "c"]));
  await flush();
  assert.equal(await tick(h, 4000), "a");
  h.observer.dispose();
});
